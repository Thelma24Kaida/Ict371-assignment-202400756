DROP VIEW IF EXISTS v_service_due CASCADE;
DROP TABLE IF EXISTS service_alerts,trips,vehicles CASCADE;
DROP FUNCTION IF EXISTS fn_service_due(integer);
DROP FUNCTION IF EXISTS trg_update_vehicle_odometer();
DROP PROCEDURE IF EXISTS pr_record_trip(integer,date,numeric,numeric);
DROP PROCEDURE IF EXISTS pr_refresh_service_alerts();

CREATE TABLE vehicles (
    vehicle_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration varchar(30) NOT NULL UNIQUE,
    current_odometer numeric(12,2) NOT NULL CHECK(current_odometer>=0),
    last_service_odometer numeric(12,2) NOT NULL CHECK(last_service_odometer>=0),
    CHECK(last_service_odometer<=current_odometer)
);
CREATE TABLE trips (
    trip_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id integer NOT NULL REFERENCES vehicles(vehicle_id),
    trip_on date NOT NULL,
    start_odometer numeric(12,2) NOT NULL CHECK(start_odometer>=0),
    end_odometer numeric(12,2) NOT NULL CHECK(end_odometer>=0),
    CHECK(end_odometer>start_odometer)
);
CREATE TABLE service_alerts (
    vehicle_id integer PRIMARY KEY REFERENCES vehicles(vehicle_id),
    km_since_service numeric(12,2) NOT NULL,
    flagged_on date NOT NULL
);

