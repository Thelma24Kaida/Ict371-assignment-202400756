CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id integer)
RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE v_current numeric(12,2); v_service numeric(12,2);
BEGIN
    SELECT current_odometer,last_service_odometer INTO v_current,v_service
    FROM vehicles WHERE vehicle_id=p_vehicle_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID %',p_vehicle_id; END IF;
    RETURN (v_current-v_service)>=5000;
END; $$;

CREATE OR REPLACE FUNCTION trg_update_vehicle_odometer()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_current numeric(12,2);
BEGIN
    SELECT current_odometer INTO v_current
    FROM vehicles WHERE vehicle_id=NEW.vehicle_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID %',NEW.vehicle_id; END IF;
    IF NEW.start_odometer<>v_current THEN
        RAISE EXCEPTION 'Trip must start at current odometer %; supplied %',v_current,NEW.start_odometer;
    END IF;
    IF NEW.end_odometer<=NEW.start_odometer THEN
        RAISE EXCEPTION 'End odometer must be greater than start odometer';
    END IF;
    UPDATE vehicles SET current_odometer=NEW.end_odometer
    WHERE vehicle_id=NEW.vehicle_id;
    RETURN NEW;
END; $$;
CREATE TRIGGER trips_update_odometer
BEFORE INSERT ON trips FOR EACH ROW
EXECUTE FUNCTION trg_update_vehicle_odometer();

CREATE OR REPLACE PROCEDURE pr_record_trip(
    p_vehicle_id integer,p_trip_on date,p_start numeric,p_end numeric
) LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM vehicles WHERE vehicle_id=p_vehicle_id) THEN
        RAISE EXCEPTION 'Unknown vehicle ID %',p_vehicle_id;
    END IF;
    IF p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL OR p_end<=p_start THEN
        RAISE EXCEPTION 'Trip date and valid increasing odometer values are required';
    END IF;
    INSERT INTO trips(vehicle_id,trip_on,start_odometer,end_odometer)
    VALUES(p_vehicle_id,p_trip_on,p_start,p_end);
    -- The BEFORE INSERT trigger alone updates current_odometer.
END; $$;

