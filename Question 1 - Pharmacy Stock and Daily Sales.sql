CREATE VIEW v_low_stock AS
SELECT medicine_id, medicine_name, unit_price, stock_qty
FROM medicines WHERE stock_qty < 10;

CREATE INDEX idx_sales_medicine_sold_on
ON sales(medicine_id, sold_on);
-- Composite index: equality on medicine_id followed by the sold_on range.
EXPLAIN
SELECT sale_id, quantity, unit_price, sold_on
FROM sales
WHERE medicine_id = 1
  AND sold_on BETWEEN CURRENT_DATE - 30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_sales(p_day date)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_day IS NULL THEN RAISE EXCEPTION 'Sales date cannot be NULL'; END IF;
    INSERT INTO daily_sales(sales_date, total_qty, total_amount)
    SELECT p_day, COALESCE(SUM(quantity), 0),
           COALESCE(SUM(quantity * unit_price), 0)::numeric(14,2)
    FROM sales WHERE sold_on = p_day
    ON CONFLICT (sales_date) DO UPDATE
    SET total_qty = EXCLUDED.total_qty,
        total_amount = EXCLUDED.total_amount;
END; $$;

-- Requires pg_cron installed and enabled by the database administrator.
-- Schedule at 00:15 daily; the command refreshes the previous calendar day.
CREATE EXTENSION IF NOT EXISTS pg_cron;
SELECT cron.schedule(
    'ict371_q1_daily_sales',
    '15 0 * * *',
    $$CALL pr_refresh_sales(CURRENT_DATE - 1);$$
