CREATE OR REPLACE FUNCTION fn_fee_balance(p_student_id integer)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due numeric(12,2); v_paid numeric(12,2);
BEGIN
    SELECT fee_due INTO v_due FROM students WHERE student_id = p_student_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student ID %', p_student_id; END IF;
    SELECT COALESCE(SUM(amount),0) INTO v_paid
    FROM payments WHERE student_id = p_student_id;
    RETURN v_due - v_paid;
END; $$;

CREATE OR REPLACE PROCEDURE pr_receive_payment(
    p_student_id integer, p_amount numeric, p_paid_on date
) LANGUAGE plpgsql AS $$
DECLARE v_balance numeric(12,2);
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 OR p_paid_on IS NULL THEN
        RAISE EXCEPTION 'Payment amount must be positive and payment date is required';
    END IF;
    PERFORM 1 FROM students WHERE student_id = p_student_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student ID %', p_student_id; END IF;
    v_balance := fn_fee_balance(p_student_id);
    IF p_amount > v_balance THEN
        RAISE EXCEPTION 'Payment % exceeds outstanding balance %', p_amount, v_balance;
    END IF;
    INSERT INTO payments(student_id, amount, paid_on)
    VALUES (p_student_id, p_amount, p_paid_on);
END; $$;

CREATE OR REPLACE FUNCTION trg_payment_audit()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO payment_audit(payment_id, student_id, amount)
    VALUES (NEW.payment_id, NEW.student_id, NEW.amount);
    RETURN NEW;
END; $$;
CREATE TRIGGER payments_audit_after_insert
AFTER INSERT ON payments FOR EACH ROW
EXECUTE FUNCTION trg_payment_audit();

