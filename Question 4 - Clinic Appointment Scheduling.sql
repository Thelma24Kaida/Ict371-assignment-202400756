CREATE OR REPLACE FUNCTION trg_check_appointment_clash()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status <> 'CANCELLED' AND EXISTS (
        SELECT 1 FROM appointments a
        WHERE a.doctor_id = NEW.doctor_id
          AND a.appointment_day = NEW.appointment_day
          AND a.slot_time = NEW.slot_time
          AND a.status <> 'CANCELLED'
          AND (TG_OP = 'INSERT' OR a.appointment_id <> NEW.appointment_id)
    ) THEN
        RAISE EXCEPTION 'Doctor % already has a non-cancelled appointment at % on %',
            NEW.doctor_id, NEW.slot_time, NEW.appointment_day;
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER appointments_no_clash
BEFORE INSERT OR UPDATE ON appointments FOR EACH ROW
EXECUTE FUNCTION trg_check_appointment_clash();

