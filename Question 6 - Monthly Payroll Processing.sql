CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id integer)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_basic numeric(12,2); v_allowance numeric(12,2); v_deduction numeric(12,2); v_net numeric(12,2);
BEGIN
    SELECT basic_salary,allowance,deduction INTO v_basic,v_allowance,v_deduction
    FROM employees WHERE employee_id=p_employee_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown employee ID %',p_employee_id; END IF;
    v_net:=v_basic+v_allowance-v_deduction;
    IF v_net<0 THEN RAISE EXCEPTION 'Computed net pay cannot be negative for employee %',p_employee_id; END IF;
    RETURN v_net;
END; $$;

CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month date)
LANGUAGE plpgsql AS $$
DECLARE e record; v_gross numeric(12,2); v_net numeric(12,2);
BEGIN
    IF p_month IS NULL OR EXTRACT(DAY FROM p_month)<>1 THEN
        RAISE EXCEPTION 'Pay month must be the first day of a month';
    END IF;
    FOR e IN SELECT employee_id,basic_salary,allowance
             FROM employees WHERE active=true ORDER BY employee_id
    LOOP
        -- Calculate every employee before inserting; any error aborts the entire call.
        v_gross:=e.basic_salary+e.allowance;
        v_net:=fn_net_pay(e.employee_id);
        INSERT INTO payroll(employee_id,pay_month,gross_pay,net_pay)
        VALUES(e.employee_id,p_month,v_gross,v_net)
        ON CONFLICT(employee_id,pay_month) DO NOTHING;
    END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION trg_salary_audit()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
        INSERT INTO salary_audit(employee_id,old_salary,new_salary)
        VALUES(NEW.employee_id,OLD.basic_salary,NEW.basic_salary);
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER employees_salary_audit
AFTER UPDATE ON employees FOR EACH ROW
EXECUTE FUNCTION trg_salary_audit();

-- At least two monthly payroll periods are represented.
CALL pr_process_payroll((DATE_TRUNC('month',CURRENT_DATE)-INTERVAL '2 months')::date);
CALL pr_process_payroll((DATE_TRUNC('month',CURRENT_DATE)-INTERVAL '1 month')::date);

CREATE VIEW v_payroll_report AS
SELECT e.employee_id,e.full_name,p.pay_month,p.gross_pay,p.net_pay
FROM payroll p JOIN employees e ON e.employee_id=p.employee_id;

CREATE INDEX idx_payroll_pay_month ON payroll(pay_month);
-- A month-leading index supports reporting across all employees for a pay month.
EXPLAIN
SELECT employee_id,gross_pay,net_pay
FROM payroll
WHERE pay_month=(DATE_TRUNC('month',CURRENT_DATE)-INTERVAL '1 month')::date;

CREATE EXTENSION IF NOT EXISTS pg_cron;
-- Run at 02:00 on day 1, processing the first date of the previous month.
SELECT cron.schedule(
    'ict371_q6_monthly_payroll',
    '0 2 1 * *',
    $$CALL pr_process_payroll((DATE_TRUNC('month',CURRENT_DATE)-INTERVAL '1 month')::date);$$
);

