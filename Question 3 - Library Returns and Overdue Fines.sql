CREATE TABLE books (
    book_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL
);
CREATE TABLE loans (
    loan_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id integer NOT NULL REFERENCES books(book_id),
    borrower_name varchar(150) NOT NULL,
    borrowed_on date NOT NULL,
    due_on date NOT NULL,
    returned_on date,
    fine_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (fine_amount >= 0),
    CHECK (due_on >= borrowed_on),
    CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);
CREATE TABLE loan_audit (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id bigint NOT NULL REFERENCES loans(loan_id),
    old_returned_on date,
    new_returned_on date,
    changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE overdue_summary (
    snapshot_date date PRIMARY KEY,
    overdue_count bigint NOT NULL,
    total_fine numeric(14,2) NOT NULL
);

