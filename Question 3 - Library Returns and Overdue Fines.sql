CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id integer, p_as_of date)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due date; v_returned date; v_end date;
BEGIN
    SELECT due_on, returned_on INTO v_due, v_returned
    FROM loans WHERE loan_id = p_loan_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %', p_loan_id; END IF;
    IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date cannot be NULL'; END IF;
    v_end := LEAST(p_as_of, COALESCE(v_returned, p_as_of));
    RETURN GREATEST(v_end - v_due, 0) * 2.00;
END; $$;

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id integer, p_returned_on date)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed date; v_due date; v_fine numeric(12,2);
BEGIN
    IF p_returned_on IS NULL THEN RAISE EXCEPTION 'Return date cannot be NULL'; END IF;
    SELECT borrowed_on, due_on INTO v_borrowed, v_due
    FROM loans WHERE loan_id = p_loan_id AND returned_on IS NULL FOR UPDATE;
    IF NOT FOUND THEN
        IF EXISTS (SELECT 1 FROM loans WHERE loan_id = p_loan_id) THEN
            RAISE EXCEPTION 'Loan % has already been returned', p_loan_id;
        ELSE
            RAISE EXCEPTION 'Unknown loan ID %', p_loan_id;
        END IF;
    END IF;
    IF p_returned_on < v_borrowed THEN RAISE EXCEPTION 'Return date cannot precede borrowing date'; END IF;
    v_fine := GREATEST(p_returned_on - v_due, 0) * 2.00;
    UPDATE loans SET returned_on = p_returned_on, fine_amount = v_fine
    WHERE loan_id = p_loan_id;
END; $$;

CREATE OR REPLACE FUNCTION trg_loan_return_audit()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
        INSERT INTO loan_audit(loan_id, old_returned_on, new_returned_on)
        VALUES (NEW.loan_id, OLD.returned_on, NEW.returned_on);
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER loans_return_audit
AFTER UPDATE ON loans FOR EACH ROW
EXECUTE FUNCTION trg_loan_return_audit();

CREATE VIEW v_overdue_loans AS
SELECT l.loan_id, b.title, l.borrower_name, l.due_on,
       fn_loan_fine(l.loan_id, CURRENT_DATE) AS fine_as_of_today
FROM loans l JOIN books b ON b.book_id = l.book_id
WHERE l.returned_on IS NULL AND l.due_on < CURRENT_DATE;

CREATE INDEX idx_loans_book_returned ON loans(book_id, returned_on);
-- Supports lookup by book and filtering for open loans (returned_on IS NULL).
