CREATE OR REPLACE FUNCTION fn_scholarship_eligible(
    p_age integer,p_income numeric,p_mark numeric
) RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
    IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN
        RAISE EXCEPTION 'Age, income and average mark cannot be NULL';
    END IF;
    IF p_age<=0 OR p_income<0 OR p_mark<0 OR p_mark>100 THEN
        RAISE EXCEPTION 'Invalid age, income or mark';
    END IF;
    RETURN p_age BETWEEN 18 AND 25
       AND p_income<=3000
       AND p_mark>=70;
END; $$;

CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id integer)
LANGUAGE plpgsql AS $$
DECLARE v_age integer; v_income numeric(12,2); v_mark numeric(5,2); v_status varchar(10);
BEGIN
    SELECT age_at_application,monthly_income,average_mark,status
    INTO v_age,v_income,v_mark,v_status
    FROM applications WHERE application_id=p_application_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown application ID %',p_application_id; END IF;
    IF v_status<>'PENDING' THEN
        RAISE EXCEPTION 'Application % has already been assessed',p_application_id;
    END IF;
    UPDATE applications
    SET status=CASE WHEN fn_scholarship_eligible(v_age,v_income,v_mark)
                    THEN 'APPROVED' ELSE 'REJECTED' END
    WHERE application_id=p_application_id;
END; $$;

CREATE OR REPLACE FUNCTION trg_decision_audit()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO decision_audit(application_id,old_status,new_status)
        VALUES(NEW.application_id,OLD.status,NEW.status);
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER applications_decision_audit
AFTER UPDATE ON applications FOR EACH ROW
EXECUTE FUNCTION trg_decision_audit();

CREATE VIEW v_approved_applicants AS
SELECT s.student_number,s.full_name,a.average_mark,a.status
FROM applications a JOIN students s ON s.student_id=a.student_id
WHERE a.status='APPROVED';

CREATE INDEX idx_applications_status_submitted
ON applications(status,submitted_on);
-- Equality on status followed by a submitted_on date range.
EXPLAIN
SELECT application_id,student_id,average_mark
FROM applications
WHERE status='PENDING'
  AND submitted_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql AS $$
DECLARE a record;
BEGIN
    FOR a IN SELECT application_id FROM applications
             WHERE status='PENDING' ORDER BY application_id
    LOOP
        CALL pr_assess_application(a.application_id::integer);
    END LOOP;
END; $$;

