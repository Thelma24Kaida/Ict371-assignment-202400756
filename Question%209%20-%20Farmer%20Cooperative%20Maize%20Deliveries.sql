CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade char)
RETURNS numeric(10,2) LANGUAGE plpgsql AS $$
BEGIN
    IF p_grade IS NULL THEN RAISE EXCEPTION 'Grade cannot be NULL'; END IF;
    CASE UPPER(p_grade)
      WHEN 'A' THEN RETURN 5.00;
      WHEN 'B' THEN RETURN 4.00;
      WHEN 'C' THEN RETURN 3.00;
      ELSE RAISE EXCEPTION 'Unsupported maize grade %',p_grade;
    END CASE;
END; $$;

CREATE OR REPLACE FUNCTION trg_price_delivery()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.weight_kg IS NULL OR NEW.weight_kg<=0 THEN
        RAISE EXCEPTION 'Delivery weight must be positive';
    END IF;
    NEW.unit_rate:=fn_maize_rate(NEW.grade);
    NEW.total_value:=NEW.weight_kg*NEW.unit_rate;
    RETURN NEW;
END; $$;
CREATE TRIGGER deliveries_set_price
BEFORE INSERT OR UPDATE ON deliveries FOR EACH ROW
EXECUTE FUNCTION trg_price_delivery();

CREATE OR REPLACE PROCEDURE pr_receive_delivery(
    p_farmer_id integer,p_grade char,p_weight numeric,p_date date
) LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM farmers WHERE farmer_id=p_farmer_id) THEN
        RAISE EXCEPTION 'Unknown farmer ID %',p_farmer_id;
    END IF;
    IF p_grade IS NULL OR UPPER(p_grade) NOT IN ('A','B','C')
       OR p_weight IS NULL OR p_weight<=0 OR p_date IS NULL THEN
        RAISE EXCEPTION 'Valid grade, positive weight and delivery date are required';
    END IF;
    -- Placeholder numeric values are overwritten by the BEFORE trigger.
    INSERT INTO deliveries(farmer_id,grade,weight_kg,unit_rate,total_value,delivered_on,is_paid)
    VALUES(p_farmer_id,UPPER(p_grade),p_weight,1,1,p_date,false);
END; $$;

