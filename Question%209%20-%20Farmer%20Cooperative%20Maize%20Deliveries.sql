CREATE VIEW v_farmer_amount_due AS
SELECT f.farmer_number,f.full_name,
       COALESCE(SUM(d.total_value) FILTER (WHERE d.is_paid=false),0)::numeric(14,2)
         AS total_unpaid_value
FROM farmers f LEFT JOIN deliveries d ON d.farmer_id=f.farmer_id
GROUP BY f.farmer_id,f.farmer_number,f.full_name;

CREATE INDEX idx_deliveries_farmer_date ON deliveries(farmer_id,delivered_on);
-- Equality on farmer_id followed by a delivery date range.
EXPLAIN
SELECT delivery_id,grade,weight_kg,total_value
FROM deliveries
WHERE farmer_id=1 AND delivered_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_purchases(p_day date)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_day IS NULL THEN RAISE EXCEPTION 'Purchase date cannot be NULL'; END IF;
    INSERT INTO daily_purchases(purchase_date,total_weight,total_value)
    SELECT p_day,COALESCE(SUM(weight_kg),0),COALESCE(SUM(total_value),0)
    FROM deliveries WHERE delivered_on=p_day
    ON CONFLICT(purchase_date) DO UPDATE
    SET total_weight=EXCLUDED.total_weight,total_value=EXCLUDED.total_value;
END; $$;

CREATE EXTENSION IF NOT EXISTS pg_cron;
SELECT cron.schedule(
    'ict371_q9_daily_purchases',
    '30 1 * * *',
    $$CALL pr_refresh_purchases(CURRENT_DATE-1);$$
